function renderNotFound() {
  const article = lines(
    '<article class="detail__body">',
    '  <h1 class="detail__title">Page not found</h1>',
    '  <p class="detail__summary">That page is not here. It may have been unpublished, or the address may be wrong.</p>',
    '  <ul class="link-list">',
    '    <li><a href="art.html">Go to Art</a></li>',
    '    <li><a href="tech.html">Go to Tech</a></li>',
    '  </ul>',
    '</article>',
  );

  return page({
    path: '404.html',
    title: 'Page not found — Jason',
    description: 'That page is not here.',
    bodyClass: 'gallery-page gallery-page--notfound',
    body: lines(siteNav('', ''), '<main id="main" class="detail">', indent(article, 2), '</main>', BACK_TO_TOP),
  });
}

