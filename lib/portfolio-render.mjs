/**
 * Render the whole public site.
 *
 * @param {object} document canonical portfolio document (drafts included)
 * @returns {Map<string, string>} relative path → HTML
 */
export function renderPortfolio(document) {
  const view = publishedPortfolio(document);
  const pages = new Map();

  pages.set('art.html', renderArtPage(view));
  pages.set('tech.html', renderTechPage(view));
  pages.set('404.html', renderNotFound());

  for (const piece of view.artPieces) {
    const [path, html] = renderPieceDetail(piece, view);
    pages.set(path, html);
  }
  for (const project of view.artProjects) {
    const [path, html] = renderArtProjectDetail(project, view);
    pages.set(path, html);
  }
  for (const project of view.techProjects) {
    const [path, html] = renderTechProjectDetail(project);
    pages.set(path, html);
  }

  return pages;
}
